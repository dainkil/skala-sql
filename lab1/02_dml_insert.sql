--
--    id 를 1, 2, 3 으로 가정하고 하드코딩하면 재실행 시 전부 깨진다.
--
--  [작성 원칙 2] VALUES 첫 행에 타입을 명시한다
--    VALUES 안의 따옴표 문자열은 타입이 unknown 이고, 서브쿼리 경계를 넘으면
--    text 로 확정된다. text → date 는 대입 캐스트가 없어 INSERT 가 실패한다.
--    그래서 날짜·시각 컬럼은 첫 행에 DATE '...' / TIMESTAMPTZ '...' 로 앵커를 박는다.
--    나머지 행은 그 타입으로 함께 해석된다.
--
--  [작성 원칙 3] NULL 은 의도적으로 심는다
--    미채점 성적, 담당교수 미배정, 미납, 사유 미기재 등은 이후
--    COALESCE / CASE WHEN / LEFT JOIN 실습의 재료다. 누락이 아니다.
-- =====================================================================

